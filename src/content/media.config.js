/**
 * Media registry — the single place that maps page slots to video files.
 *
 * Each entry maps a page slot to ready-to-play media under public/.
 *
 *   id            unique id used by the page
 *   section       hero | control | grounding | dashcam | long
 *   controlType   sub-type inside a section (lane, road_marker, traffic_light, first_frame, reference_images, 3dgs …)
 *   source        optional original file under the assets root; omit for committed, ready-to-play public/ media
 *   assetRoot     optional sibling folder of this project (e.g. final-assets); defaults to assets
 *   src           web file, relative to public/ (what the page loads)
 *   poster        poster image, relative to public/ (generated by the script at `posterAt` seconds)
 *   isReference   true = reference / placeholder clip, shows the "reference clip" badge (see site.config flags)
 *   sharedWith    optional note: other entries currently using the same placeholder footage
 *   autoplay      play muted when the stage scrolls into view (respects reduced-motion preference)
 *   loop          loop the clip while its stage is visible
 *   title / description / inputLabel / outputLabel / renderNote   bilingual { en, zh }
 *
 * Width, height, duration, frame count and fps are probed by the script and written to
 * media.meta.generated.js, so replacing a file automatically updates aspect ratio and durations.
 */

